#!/usr/bin/env python3

from dataclasses import dataclass, field

from tools.finding_extractor import Finding


@dataclass
class ClassificationMapping:
    value: str
    source: str
    confidence: str
    status: str


@dataclass
class SourceClassification:
    """Classification references declared in the original report."""

    category: str | None = None
    owasp: list[str] = field(default_factory=list)
    cwe: list[str] = field(default_factory=list)
    cve: list[str] = field(default_factory=list)


@dataclass
class KnowledgeBaseClassification:
    """Classification suggestions generated by the AI-OSF registry."""

    category: ClassificationMapping | None = None
    owasp: list[ClassificationMapping] = field(default_factory=list)
    cwe: list[ClassificationMapping] = field(default_factory=list)


@dataclass
class ClassificationResult:
    writeup_id: str
    original_vulnerabilities: list[str] = field(default_factory=list)
    normalized_vulnerabilities: list[str] = field(default_factory=list)
    source_report: SourceClassification = field(
        default_factory=SourceClassification
    )
    knowledge_base: KnowledgeBaseClassification = field(
        default_factory=KnowledgeBaseClassification
    )
    related_concepts: list[str] = field(default_factory=list)

    # Backwards-compatible access to knowledge base suggestions.
    @property
    def category(self):
        return self.knowledge_base.category

    @property
    def owasp(self):
        return self.knowledge_base.owasp

    @property
    def cwe(self):
        return self.knowledge_base.cwe


VULNERABILITY_REGISTRY = {
    "bola": {
        "canonical_name": "Broken Object Level Authorization",
        "aliases": [
            "bola",
            "broken object level authorization",
            "broken object-level authorization",
        ],
        "category": "API Security",
        "owasp": "API1:2023",
        "cwe": [
            {
                "value": "CWE-639",
                "confidence": "medium",
                "status": "potential",
            }
        ],
        "related_concepts": [
            "IDOR",
            "Object-level access control",
        ],
    }
}


def normalize_name(value: str) -> str:
    """Normalize a vulnerability label for matching."""

    return " ".join(value.strip().lower().split())


def normalize_reference_list(value) -> list[str]:
    """Normalize source references without modifying their values."""

    if isinstance(value, str):
        value = [value]

    if not isinstance(value, list):
        return []

    return [
        item.strip()
        for item in value
        if isinstance(item, str) and item.strip()
    ]


def extract_source_classification(
    classification: dict | None,
) -> SourceClassification:
    """Preserve classification references declared by the report."""

    if not isinstance(classification, dict):
        return SourceClassification()

    category = classification.get("category")

    if not isinstance(category, str) or not category.strip():
        category = None
    else:
        category = category.strip()

    return SourceClassification(
        category=category,
        owasp=normalize_reference_list(
            classification.get("owasp")
        ),
        cwe=normalize_reference_list(
            classification.get("cwe")
        ),
        cve=normalize_reference_list(
            classification.get("cve")
        ),
    )


def classify_vulnerability(name: str) -> dict | None:
    """Find a vulnerability in the classification registry."""

    normalized = normalize_name(name)

    for key, definition in VULNERABILITY_REGISTRY.items():
        aliases = [
            normalize_name(alias)
            for alias in definition["aliases"]
        ]

        if normalized in aliases:
            return {
                "key": key,
                "definition": definition,
            }

    return None


def classify_finding(
    finding: Finding,
    source_classification: dict | None = None,
) -> ClassificationResult:
    """
    Classify a Finding without modifying its original data.

    Source report references and knowledge base suggestions
    are stored separately.
    """

    result = ClassificationResult(
        writeup_id=finding.writeup_id,
        original_vulnerabilities=list(finding.vulnerabilities),
        source_report=extract_source_classification(
            source_classification
        ),
    )

    for vulnerability in finding.vulnerabilities:
        match = classify_vulnerability(vulnerability)

        if match is None:
            continue

        definition = match["definition"]
        canonical_name = definition["canonical_name"]

        if canonical_name not in result.normalized_vulnerabilities:
            result.normalized_vulnerabilities.append(canonical_name)

        knowledge_base = result.knowledge_base

        if knowledge_base.category is None:
            knowledge_base.category = ClassificationMapping(
                value=definition["category"],
                source="knowledge_base",
                confidence="high",
                status="suggested",
            )

        owasp_reference = ClassificationMapping(
            value=definition["owasp"],
            source="knowledge_base",
            confidence="high",
            status="suggested",
        )

        if owasp_reference.value not in [
            item.value for item in knowledge_base.owasp
        ]:
            knowledge_base.owasp.append(owasp_reference)

        for cwe_reference in definition["cwe"]:
            reference = ClassificationMapping(
                value=cwe_reference["value"],
                source="knowledge_base",
                confidence=cwe_reference["confidence"],
                status=cwe_reference["status"],
            )

            if reference.value not in [
                item.value for item in knowledge_base.cwe
            ]:
                knowledge_base.cwe.append(reference)

        for concept in definition["related_concepts"]:
            if concept not in result.related_concepts:
                result.related_concepts.append(concept)

    return result
